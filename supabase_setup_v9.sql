create or replace function public.normalize_jordan_phone(p_phone text)
returns text
language plpgsql
immutable
as $$
declare
  v text := regexp_replace(coalesce(p_phone,''),'[^0-9+]','','g');
begin
  if v ~ '^07[0-9]{8}$' then
    return '+962' || substr(v,2);
  elsif v ~ '^\+9627[0-9]{8}$' then
    return v;
  elsif v ~ '^9627[0-9]{8}$' then
    return '+' || v;
  end if;
  return null;
end $$;

create or replace function public.new_referral_code()
returns text
language plpgsql
volatile
security definer
set search_path=public
as $$
declare
  v text;
begin
  loop
    v := 'CRV' || upper(substr(encode(gen_random_bytes(5),'hex'),1,7));
    exit when not exists(select 1 from public.profiles where upper(referral_code)=v);
  end loop;
  return v;
end $$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  insert into public.profiles(id,display_name,referral_code)
  values(
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data->>'display_name'),''),'Member'),
    public.new_referral_code()
  )
  on conflict(id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Fill referral codes for old accounts.
do $$
declare r record;
begin
  for r in select id from public.profiles where referral_code is null loop
    update public.profiles set referral_code=public.new_referral_code() where id=r.id;
  end loop;
end $$;

create or replace function public.is_current_user_admin()
returns boolean
language sql
stable
security definer
set search_path=public
as $$
  select coalesce((select is_admin from public.profiles where id=auth.uid()),false)
$$;

