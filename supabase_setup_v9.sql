create or replace function public.create_crava_order(
  p_customer_name text,
  p_phone text,
  p_area text,
  p_street text,
  p_building text,
  p_floor text default null,
  p_apartment text default null,
  p_order_notes text default null,
  p_box_size_code text default null,
  p_cookie_selections jsonb default '[]'::jsonb,
  p_roll_selections jsonb default '[]'::jsonb,
  p_points_to_use integer default 0,
  p_referral_code text default null
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_user uuid := auth.uid();
  v_profile public.profiles;
  v_size public.box_sizes;
  v_area public.delivery_areas;
  v_phone text;
  v_order public.orders;
  v_code text;
  v_option public.flavor_options;
  v_pos integer;
  v_points integer := coalesce(p_points_to_use,0);
  v_discount numeric(10,3);
  v_total numeric(10,3);
  v_referrer public.profiles;
  v_existing_ref public.referrals;
  v_ref_code text := upper(trim(coalesce(p_referral_code,'')));
begin
  if v_user is null then
    raise exception 'SIGN IN REQUIRED';
  end if;

  select * into v_profile from public.profiles where id=v_user for update;
  if not found then
    raise exception 'PROFILE NOT FOUND';
  end if;

  if char_length(trim(coalesce(p_customer_name,''))) < 2 then
    raise exception 'INVALID CUSTOMER NAME';
  end if;

  v_phone := public.normalize_jordan_phone(p_phone);
  if v_phone is null then
    raise exception 'INVALID JORDAN PHONE';
  end if;

  if char_length(trim(coalesce(p_street,''))) < 2 or char_length(trim(coalesce(p_building,''))) < 1 then
    raise exception 'INCOMPLETE ADDRESS';
  end if;

  select * into v_area
  from public.delivery_areas
  where is_active=true and name_ar=trim(coalesce(p_area,''));
  if not found then
    raise exception 'DELIVERY OUTSIDE AMMAN';
  end if;

  select * into v_size
  from public.box_sizes
  where code=upper(trim(coalesce(p_box_size_code,''))) and is_active=true;
  if not found then
    raise exception 'INVALID BOX SIZE';
  end if;

  if jsonb_typeof(p_cookie_selections) <> 'array'
     or jsonb_array_length(p_cookie_selections) <> v_size.cookie_count then
    raise exception 'COOKIE SELECTIONS INCOMPLETE';
  end if;

  if jsonb_typeof(p_roll_selections) <> 'array'
     or jsonb_array_length(p_roll_selections) <> v_size.roll_count then
    raise exception 'ROLL SELECTIONS INCOMPLETE';
  end if;

  -- Validate all selected option codes before creating anything.
  for v_code in select jsonb_array_elements_text(p_cookie_selections) loop
    if not exists(select 1 from public.flavor_options where code=v_code and item_type='cookie' and is_active=true) then
      raise exception 'INVALID COOKIE OPTION';
    end if;
  end loop;

  for v_code in select jsonb_array_elements_text(p_roll_selections) loop
    if not exists(select 1 from public.flavor_options where code=v_code and item_type='roll' and is_active=true) then
      raise exception 'INVALID ROLL OPTION';
    end if;
  end loop;

  if v_points < 0 or v_points > 100 then
    raise exception 'POINTS LIMIT IS 100';
  end if;
  if v_points > v_profile.points then
    raise exception 'INSUFFICIENT POINTS';
  end if;

  v_discount := round((v_points::numeric / 100.0),3);
  v_total := greatest(round(v_size.price + v_area.delivery_fee - v_discount,3),0);

  if v_ref_code <> '' then
    select * into v_referrer
    from public.profiles
    where upper(referral_code)=v_ref_code;

    if not found then
      raise exception 'INVALID REFERRAL CODE';
    end if;
    if v_referrer.id=v_user then
      raise exception 'CANNOT USE OWN REFERRAL CODE';
    end if;

    select * into v_existing_ref
    from public.referrals
    where referred_user_id=v_user
    for update;

    if found and v_existing_ref.reward_status='rewarded' then
      raise exception 'REFERRAL ALREADY USED';
    elsif found and v_existing_ref.inviter_id<>v_referrer.id then
      raise exception 'REFERRAL ALREADY REGISTERED';
    end if;
  end if;

  insert into public.orders(
    user_id,customer_name,phone_e164,area,street,building,floor,apartment,order_notes,
    box_size_code,box_name,box_price,subtotal,delivery_fee,points_used,points_discount,total,
    points_balance_after,referral_code,referrer_id,payment_method,status
  ) values(
    v_user,trim(p_customer_name),v_phone,v_area.name_ar,trim(p_street),trim(p_building),
    nullif(trim(coalesce(p_floor,'')),''),nullif(trim(coalesce(p_apartment,'')),''),
    nullif(trim(coalesce(p_order_notes,'')),''),v_size.code,v_size.name_ar,v_size.price,
    v_size.price,v_area.delivery_fee,v_points,v_discount,v_total,v_profile.points-v_points,
    nullif(v_ref_code,''),case when v_ref_code='' then null else v_referrer.id end,
    'cash_on_delivery','new'
  ) returning * into v_order;

  v_pos := 0;
  for v_code in select jsonb_array_elements_text(p_cookie_selections) loop
    v_pos := v_pos + 1;
    select * into v_option from public.flavor_options where code=v_code;
    insert into public.order_items(order_id,item_type,position,option_code,option_name,category_name,quantity,unit_price)
    values(v_order.id,'cookie',v_pos,v_option.code,v_option.name_ar,v_option.category_name,1,0);
  end loop;

  v_pos := 0;
  for v_code in select jsonb_array_elements_text(p_roll_selections) loop
    v_pos := v_pos + 1;
    select * into v_option from public.flavor_options where code=v_code;
    insert into public.order_items(order_id,item_type,position,option_code,option_name,category_name,quantity,unit_price)
    values(v_order.id,'roll',v_pos,v_option.code,v_option.name_ar,v_option.category_name,1,0);
  end loop;

  insert into public.order_items(order_id,item_type,position,option_code,option_name,category_name,quantity,unit_price)
  values(v_order.id,'candy',1,'orbs','Orbs','Candy',1,0);

  if v_points > 0 then
    update public.profiles
    set points=points-v_points,
        phone_e164=v_phone,
        display_name=trim(p_customer_name),
        updated_at=now()
    where id=v_user;

    insert into public.points_ledger(user_id,order_id,points,reason,transaction_key)
    values(v_user,v_order.id,-v_points,'استخدام نقاط في الطلب #' || lpad(v_order.order_number::text,6,'0'),'order-use-' || v_order.id::text);
  else
    update public.profiles
    set phone_e164=v_phone,
        display_name=trim(p_customer_name),
        updated_at=now()
    where id=v_user;
  end if;

  if v_ref_code <> '' then
    insert into public.referrals(inviter_id,referred_user_id,referral_code,qualifying_order_id,reward_status)
    values(v_referrer.id,v_user,v_ref_code,v_order.id,'pending')
    on conflict(referred_user_id) do update set
      qualifying_order_id=excluded.qualifying_order_id,
      referral_code=excluded.referral_code,
      inviter_id=excluded.inviter_id,
      reward_status='pending',
      updated_at=now()
    where public.referrals.reward_status<>'rewarded';

    update public.profiles set referred_by=v_referrer.id,updated_at=now()
    where id=v_user and referred_by is null;
  end if;

  return jsonb_build_object(
    'ok',true,
    'order_id',v_order.id,
    'order_number',v_order.order_number,
    'subtotal',v_order.subtotal,
    'delivery_fee',v_order.delivery_fee,
    'points_used',v_order.points_used,
    'points_discount',v_order.points_discount,
    'total',v_order.total,
    'points_balance_after',v_order.points_balance_after
  );
end $$;

