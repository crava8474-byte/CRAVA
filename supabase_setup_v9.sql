create or replace function public.admin_update_order_status(
  p_order_id uuid,
  p_status text,
  p_admin_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_order public.orders;
  v_ref public.referrals;
  v_new_balance integer;
begin
  if not public.is_current_user_admin() then raise exception 'ACCESS DENIED'; end if;
  if p_status not in('new','confirmed','preparing','out_for_delivery','delivered','cancelled') then
    raise exception 'INVALID STATUS';
  end if;

  select * into v_order from public.orders where id=p_order_id for update;
  if not found then raise exception 'ORDER NOT FOUND'; end if;
  if v_order.status='cancelled' and p_status<>'cancelled' then
    raise exception 'CANCELLED ORDER IS FINAL';
  end if;

  update public.orders set
    status=p_status,
    admin_note=coalesce(nullif(trim(coalesce(p_admin_note,'')),''),admin_note),
    delivered_at=case when p_status='delivered' then coalesce(delivered_at,now()) else delivered_at end,
    cancelled_at=case when p_status='cancelled' then coalesce(cancelled_at,now()) else cancelled_at end,
    updated_at=now()
  where id=p_order_id
  returning * into v_order;

  -- Refund redeemed points exactly once when an order is cancelled.
  if p_status='cancelled' and v_order.points_used>0 and v_order.points_refunded_at is null then
    update public.profiles
    set points=points+v_order.points_used,updated_at=now()
    where id=v_order.user_id
    returning points into v_new_balance;

    insert into public.points_ledger(user_id,order_id,points,reason,transaction_key)
    values(v_order.user_id,v_order.id,v_order.points_used,'إرجاع نقاط الطلب الملغي #' || lpad(v_order.order_number::text,6,'0'),'order-refund-' || v_order.id::text)
    on conflict(transaction_key) do nothing;

    update public.orders
    set points_refunded_at=now(),points_balance_after=v_new_balance,updated_at=now()
    where id=v_order.id
    returning * into v_order;
  end if;

  -- Reward the inviter only once, and only after delivery.
  if p_status='delivered' then
    select * into v_ref
    from public.referrals
    where qualifying_order_id=v_order.id and reward_status='pending'
    for update;

    if found then
      update public.profiles set xp=xp+v_ref.reward_xp,updated_at=now() where id=v_ref.inviter_id;
      update public.referrals set reward_status='rewarded',rewarded_at=now(),updated_at=now() where id=v_ref.id;
      update public.orders set referral_rewarded_at=now(),updated_at=now() where id=v_order.id returning * into v_order;
    end if;
  elsif p_status='cancelled' then
    update public.referrals
    set reward_status='cancelled',updated_at=now()
    where qualifying_order_id=v_order.id and reward_status='pending';
  end if;

  return jsonb_build_object(
    'ok',true,
    'order_id',v_order.id,
    'order_number',v_order.order_number,
    'status',v_order.status,
    'points_refunded',v_order.points_refunded_at is not null,
    'referral_rewarded',v_order.referral_rewarded_at is not null
  );
end $$;

