-- Optional helper: generates only missing physical boxes and returns their raw codes once.
create or replace function public.admin_generate_boxes(p_from integer,p_to integer)
returns table(box_number integer,claim_code text)
language plpgsql
security definer
set search_path=public
as $$
declare i integer; v_code text;
begin
  if not public.is_current_user_admin() then raise exception 'ACCESS DENIED'; end if;
  if p_from<1 or p_to<p_from or p_to-p_from>1000 then raise exception 'INVALID RANGE'; end if;

  for i in p_from..p_to loop
    if not exists(select 1 from public.boxes where public.boxes.box_number=i) then
      v_code:=upper(substr(encode(gen_random_bytes(8),'hex'),1,8));
      insert into public.boxes(box_number,claim_code_hash) values(i,crypt(v_code,gen_salt('bf')));
      box_number:=i;
      claim_code:=v_code;
      return next;
    end if;
  end loop;
end $$;

